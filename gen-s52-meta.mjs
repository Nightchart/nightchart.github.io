const out = [];
for (const [dir, prim] of Object.entries(DIRS)) {
  const full = path.join(ROOT, 'assets', 's52', dir);
  for (const f of fs.readdirSync(full).filter((x) => x.endsWith('.svg')).sort()) {
    const stem = f.replace(/\.svg$/, '');
    let m = stem.match(/^([A-Z]+[0-9a-z]*)_?(.*)$/);
    if (stem === 'rock_ledge') m = ['rock_ledge', 'K_ledge', 'rock ledge'];
    const int1 = m ? m[1] : stem;
    if (!ZH[stem]) throw new Error('缺少中文注释: ' + stem);
    out.push({
      f: `assets/s52/${dir}/${f}`,
      int1,
      en: (m && m[2] ? m[2] : stem).replace(/^(\d+)_/, '').replace(/_/g, ' '),
      zh: ZH[stem],
      cat: int1.replace(/[0-9a-z]/g, '')[0] || '?',
      prim,
      obj: OBJ[stem] || '',
    });
  }
}
const missing = out.filter((s) => !CATS[s.cat]);
if (missing.length) throw new Error('未知类别: ' + missing.map((s) => s.f).join(', '));
out.sort((a, b) => (a.cat + a.int1).localeCompare(b.cat + b.int1) || a.f.localeCompare(b.f));
fs.writeFileSync(
  path.join(ROOT, 'data', 's52', 'symbols.json'),
  JSON.stringify({ cats: CATS, syms: out }, null, 1) + '\n',
);
console.log(`OK ${out.length} symbols, cats=${Object.keys(CATS).length}`);
